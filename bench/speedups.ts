// Writes src/speedups.ts, the measured speed-ups optilint ships, from a `bun run bench --tiers all --json` file.
// Usage: bun bench/speedups.ts [results.json] (default: the newest in bench/results/).
import fs from "node:fs";
import path from "node:path";
import { loadCases, UNSTEADY } from "./gen.ts";
import { TIERS } from "./tiers.ts";

export const OUT = path.join(import.meta.dirname, "..", "src", "speedups.ts");
const RESULTS = path.join(import.meta.dirname, "results");

interface Results {
  date: string; node: string; bun: string;
  results: { tier: string; id: string; size: number; before: number; after: number; spread: number }[];
}

export const newestResults = () => {
  const files = fs.readdirSync(RESULTS).filter((f) => f.endsWith(".json")).sort();
  if (!files.length) throw new Error(`no results in ${RESULTS}; run bun run bench --tiers all --json bench/results/DATE.json`);
  return path.join(RESULTS, files.at(-1)!);
};

/** Ids of the cases marked `outOfScope`: benched, but not part of what a fix promises. */
export async function outOfScopeIds(): Promise<Set<string>> {
  const cases = (await loadCases()).flatMap((f) => f.cases).filter((c) => c.outOfScope);
  return new Set(cases.map((c) => (c.name ? `${c.rule}:${c.name}` : c.rule)));
}

/** The text of src/speedups.ts for one results file, and the unsteady cells it left out. */
export function render(file: string, outOfScope: ReadonlySet<string> = new Set()): { text: string; skipped: string[] } {
  const data = JSON.parse(fs.readFileSync(file, "utf8")) as Results;
  const engineOf = new Map(TIERS.map((t) => [t.id, t.cmd === "node" ? "v8" : "jsc"] as const));
  const byRule = new Map<string, { v8: number[]; jsc: number[] }>();
  const skipped: string[] = [];
  for (const r of data.results) {
    if (outOfScope.has(r.id)) continue;
    if (r.spread > UNSTEADY) {
      skipped.push(`${r.id} @${r.size} on ${r.tier}`);
      continue;
    }
    const rule = r.id.split(":")[0]!;
    const engine = engineOf.get(r.tier);
    if (!engine) throw new Error(`unknown tier ${r.tier} in ${file}`);
    if (!byRule.has(rule)) byRule.set(rule, { v8: [], jsc: [] });
    byRule.get(rule)![engine].push(r.before / r.after);
  }
  const round = (n: number) => Math.round(n * 100) / 100;
  const range = (xs: number[]) => {
    if (!xs.length) throw new Error(`${file}: an engine has no steady result for a rule; re-run it`);
    return `{ worst: ${round(Math.min(...xs))}, best: ${round(Math.max(...xs))} }`;
  };
  const rows = [...byRule].sort(([a], [b]) => a.localeCompare(b))
    .map(([rule, e]) => `  ${JSON.stringify(rule)}: { v8: ${range(e.v8)}, jsc: ${range(e.jsc)} },`);
  const source = path.relative(path.dirname(OUT), file).split(path.sep).join("/");
  const text = `// Generated by \`bun run bench:speedups\` from ${source}; do not edit.
// Before ÷ after time of each rule's fix, worst and best over every tier and size (\`bench/README.md\`).

export interface Speedup { worst: number; best: number }

export const MEASURED = { date: ${JSON.stringify(data.date.slice(0, 10))}, node: ${JSON.stringify(data.node)}, bun: ${JSON.stringify(data.bun)} };

export const SPEEDUPS: Readonly<Record<string, { v8: Speedup; jsc: Speedup }>> = {
${rows.join("\n")}
};

/** The lowest measured speed-up of a rule's fix on any engine; undefined when it was not measured. */
export function worstSpeedup(rule: string): number | undefined {
  const s = SPEEDUPS[rule];
  return s && Math.min(s.v8.worst, s.jsc.worst);
}
`;
  return { text, skipped };
}

if (import.meta.main) {
  const file = path.resolve(process.argv[2] ?? newestResults());
  const { text, skipped } = render(file, await outOfScopeIds());
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} from ${path.relative(process.cwd(), file)}`);
  if (skipped.length) console.log(`left out ${skipped.length} unsteady results:\n  ${skipped.join("\n  ")}`);
}
